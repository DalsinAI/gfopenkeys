#!/usr/bin/env python3
"""Writes gfopenkeys.library's fd, clib, proto and inline headers from the
one table below, so they can't disagree. Run from the repository root.
MIT, Copyright (c) 2026 AmiCradle Team."""
import os

BIAS = 30
BASE = "GFOpenKeysBase"
# name, return type, [(argument type, name, register)]; the order is the LVO order (DESIGN.md section 2)
CALLS = [
    ("GK_Version", "ULONG", []),
    ("GK_Find", "LONG", [("CONST_STRPTR", "service", "a0"), ("CONST_STRPTR", "host", "a1"), ("CONST_STRPTR", "user", "a2"),
                         ("UBYTE *", "buf", "a3"), ("ULONG *", "len", "d0"), ("ULONG", "flags", "d1")]),
    ("GK_Store", "LONG", [("CONST_STRPTR", "service", "a0"), ("CONST_STRPTR", "host", "a1"), ("CONST_STRPTR", "user", "a2"),
                          ("CONST UBYTE *", "secret", "a3"), ("ULONG", "len", "d0"), ("CONST_STRPTR", "label", "d1"),
                          ("ULONG", "flags", "d2")]),
    ("GK_Delete", "LONG", [("CONST_STRPTR", "service", "a0"), ("CONST_STRPTR", "host", "a1"), ("CONST_STRPTR", "user", "a2"),
                           ("ULONG", "flags", "d0")]),
    ("GK_List", "LONG", [("struct Hook *", "hook", "a0"), ("CONST_STRPTR", "service", "a1"), ("ULONG", "flags", "d0")]),
    ("GK_Unlock", "LONG", [("struct Window *", "parent", "a0"), ("ULONG", "flags", "d0")]),
    ("GK_Lock", None, []),
    ("GK_Status", "LONG", [("struct GKStatus *", "status", "a0")]),
    ("GK_SetTimeout", "LONG", [("ULONG", "seconds", "d0")]),
    ("GK_ChangePassphrase", "LONG", [("struct Window *", "parent", "a0"), ("ULONG", "flags", "d0")]),
    ("GK_Import", "LONG", [("CONST struct GKImport *", "list", "a0"), ("ULONG", "count", "d0"),
                           ("CONST_STRPTR", "from", "a1"), ("ULONG", "flags", "d1")]),
    ("GK_ErrorString", "CONST_STRPTR", [("LONG", "error", "d0")]),
]
HEAD = "/* Generated by tools/gen_headers.py: do not edit. MIT, Copyright (c) 2026 AmiCradle Team. */\n"


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def main():
    fd = ["* gfopenkeys.library, version 1. Generated by tools/gen_headers.py", "##base _" + BASE,
          "##bias %d" % BIAS, "##public"]
    clib = [HEAD, "#ifndef CLIB_GFOPENKEYS_PROTOS_H", "#define CLIB_GFOPENKEYS_PROTOS_H", "",
            "#include <exec/types.h>", "#include <utility/hooks.h>", "#include <intuition/intuition.h>",
            "#include <libraries/gfopenkeys.h>", ""]
    inl = [HEAD, "#ifndef INLINE_GFOPENKEYS_H", "#define INLINE_GFOPENKEYS_H", "",
           "#ifndef __INLINE_MACROS_H", "#include <inline/macros.h>", "#endif", "",
           "#ifndef GFOPENKEYS_BASE_NAME", "#define GFOPENKEYS_BASE_NAME " + BASE, "#endif", ""]
    for i, (name, ret, args) in enumerate(CALLS):
        off = BIAS + 6 * i
        fd.append("%s(%s)(%s)" % (name, ",".join(a[1] for a in args), "/".join(a[2] for a in args)))
        clib.append("%s %s(%s);" % (ret or "VOID", name, ", ".join("%s%s%s" % (t, "" if t.endswith("*") else " ", n)
                                                                     for t, n, _ in args) or "VOID"))
        params = ", ".join(a[1] for a in args)
        margs = "".join("%s, %s, %s, " % (t, n, r) for t, n, r in args)
        if ret:
            body = "LP%d(0x%x, %s, %s, %s, GFOPENKEYS_BASE_NAME)" % (len(args), off, ret, name, margs)
        else:
            body = "LP%dNR(0x%x, %s, %s, GFOPENKEYS_BASE_NAME)" % (len(args), off, name, margs)
        inl += ["#define %s(%s) \\" % (name, params), "\t" + body, ""]
    fd.append("##end")
    clib += ["", "#endif"]
    inl += ["#endif"]
    proto = [HEAD.rstrip(), "#ifndef PROTO_GFOPENKEYS_H", "#define PROTO_GFOPENKEYS_H", "",
             "#include <exec/types.h>", "#include <exec/libraries.h>", "#include <libraries/gfopenkeys.h>", "",
             "#ifndef __NOLIBBASE__", "extern struct Library *" + BASE + ";", "#endif", "",
             "#if defined(__GNUC__)", "#include <inline/gfopenkeys.h>", "#else",
             "#include <clib/gfopenkeys_protos.h>", "#endif", "", "#endif", ""]
    write("include/fd/gfopenkeys_lib.fd", "\n".join(fd) + "\n")
    write("include/clib/gfopenkeys_protos.h", "\n".join(clib) + "\n")
    write("include/inline/gfopenkeys.h", "\n".join(inl) + "\n")
    write("include/proto/gfopenkeys.h", "\n".join(proto))


if __name__ == "__main__":
    main()
